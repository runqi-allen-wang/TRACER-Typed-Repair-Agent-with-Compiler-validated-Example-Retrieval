"""Run the 12-core/4-challenge LeanCapsule clean-replay experiment."""

from __future__ import annotations

import argparse
import json
import platform
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import summarize_capsule_challenges as engine  # noqa: E402


CORE_ROOT = ROOT / "gallery_sources" / "core"
CHALLENGE_ROOT = ROOT / "gallery_sources" / "challenge"
RESULTS_ROOT = ROOT / "results" / "capsule_feasibility"
CHALLENGE_RESULTS = ROOT / "results" / "capsule_challenges"
REPORT = ROOT / "docs" / "CAPSULE_FEASIBILITY.md"


def core_case_passed(result: dict[str, Any]) -> bool:
    required = (
        "correct_template_compile_ok",
        "error_version_failed_as_expected",
        "setup_ok",
        "pack_ok",
        "official_compile_status_preserved",
        "official_error_category_preserved",
        "official_diagnostic_key_preserved",
        "replay_success",
        "strict_ordered_diagnostics_preserved",
    )
    return all(result.get(field) is True for field in required)


def _context(case_id: str) -> str:
    if case_id.endswith("_project_local"):
        return "project-local"
    if case_id.endswith("_same_file"):
        return "same-file"
    return "standalone"


def render_markdown(payload: dict[str, Any]) -> str:
    core_summary = payload["core_summary"]
    challenge_summary = payload["challenge_summary"]
    lines = [
        "# LeanCapsule 12-core / 4-challenge feasibility experiment",
        "",
        "> Generated by `scripts/run_capsule_feasibility.py`; measured values must not be edited by hand.",
        "",
        "## Result",
        "",
        f"- Core gate: **{payload['core_passed_count']}/12 passed**.",
        f"- Challenge clean replay: **{challenge_summary['replay_success_count']}/4**.",
        f"- All-case diagnostic-key preservation: **{payload['all_summary']['official_diagnostic_key_preserved_count']}/16**.",
        f"- All-case clean replay: **{payload['all_summary']['replay_success_count']}/16**.",
        f"- Core standalone/fallback: **{core_summary['standalone_count']}/{core_summary['full_file_fallback_count']}**.",
        "",
        "## Core cases",
        "",
        "| case | taxonomy | context | extraction | key preserved | clean replay | core gate |",
        "|---|---|---|---|---:|---:|---:|",
    ]
    for result in payload["core_cases"]:
        lines.append(
            f"| `{result['case_id']}` | {result['taxonomy']} | {_context(result['case_id'])} | "
            f"`{result['extraction_mode']}` | {'yes' if result['official_diagnostic_key_preserved'] else 'no'} | "
            f"{'yes' if result['replay_success'] else 'no'} | {'pass' if core_case_passed(result) else 'fail'} |"
        )
    lines.extend(
        [
            "",
            "## Challenge cases",
            "",
            "| case | extraction | key preserved | clean replay | strict ordered text |",
            "|---|---|---:|---:|---:|",
        ]
    )
    for result in payload["challenge_cases"]:
        lines.append(
            f"| `{result['case_id']}` | `{result['extraction_mode']}` | "
            f"{'yes' if result['official_diagnostic_key_preserved'] else 'no'} | "
            f"{'yes' if result['replay_success'] else 'no'} | "
            f"{'yes' if result['strict_ordered_diagnostics_preserved'] else 'no'} |"
        )
    lines.extend(
        [
            "",
            "## Protocol",
            "",
            "Each case contains a compiling `Correct.lean` and a one-line-mutated failing `Error.lean`. "
            "The runner compiles both, packs the failing theorem, copies the capsule to a fresh temporary directory, "
            "rebuilds project-local Lean sources when required, and compares compile status, category, diagnostic key, "
            "and the complete ordered normalized diagnostic text.",
            "",
            "The 12 core cases are a hard gate. Challenge outcomes are always retained rather than filtered. "
            "This finite synthetic experiment demonstrates the implemented matrix only; it is not evidence for arbitrary Lake projects.",
            "",
            "## Reproduce",
            "",
            "```bash",
            "python scripts/run_capsule_feasibility.py",
            "python -m unittest tests.test_capsule_feasibility tests.test_capsule_challenges tests.test_capsule -v",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--timeout", type=float, default=60.0)
    parser.add_argument(
        "--verify-only",
        action="store_true",
        help="在仓库内的临时目录复验，不覆盖已发布的结果与报告。",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    engine.ensure_elan_home()
    core_cases = engine.discover_cases(CORE_ROOT)
    challenge_cases = engine.discover_cases(CHALLENGE_ROOT)
    if len(core_cases) != 12 or len(challenge_cases) != 4:
        raise SystemExit(f"expected 12 core and 4 challenge cases, found {len(core_cases)} and {len(challenge_cases)}")

    temporary: tempfile.TemporaryDirectory[str] | None = None
    if args.verify_only:
        (ROOT / "results").mkdir(parents=True, exist_ok=True)
        temporary = tempfile.TemporaryDirectory(prefix=".feasibility-check-", dir=ROOT / "results")
        check_root = Path(temporary.name)
        results_root = check_root / "core"
        challenge_results = check_root / "challenge"
    else:
        results_root = RESULTS_ROOT
        challenge_results = CHALLENGE_RESULTS

    core_capsules = results_root / "capsules"
    challenge_capsules = challenge_results / "capsules"
    core_capsules.mkdir(parents=True, exist_ok=True)
    challenge_capsules.mkdir(parents=True, exist_ok=True)
    core_results = [engine.run_case(case, core_capsules, args.timeout) for case in core_cases]
    challenge_results = [engine.run_case(case, challenge_capsules, args.timeout) for case in challenge_cases]
    all_results = [*core_results, *challenge_results]
    payload = {
        "experiment": "leancapsule-feasibility-v1",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "environment": {
            "git_commit": engine._git_value("rev-parse", "HEAD"),
            "git_branch": engine._git_value("branch", "--show-current"),
            "lean_version": engine._version(["lean", "--version"]),
            "python_version": platform.python_version(),
            "platform": f"{platform.system()}-{platform.machine()}",
        },
        "core_passed_count": sum(core_case_passed(result) for result in core_results),
        "core_cases": core_results,
        "challenge_cases": challenge_results,
        "core_summary": engine.summarize(core_results),
        "challenge_summary": engine.summarize(challenge_results),
        "all_summary": engine.summarize(all_results),
    }
    if not args.verify_only:
        RESULTS_ROOT.mkdir(parents=True, exist_ok=True)
        markdown = render_markdown(payload)
        (RESULTS_ROOT / "summary.json").write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        (RESULTS_ROOT / "summary.md").write_text(markdown, encoding="utf-8")
        REPORT.write_text(markdown, encoding="utf-8")
    print(
        json.dumps(
            {
                "ok": payload["core_passed_count"] == 12,
                "core_passed": payload["core_passed_count"],
                "challenge_replay": payload["challenge_summary"]["replay_success_count"],
                "all_replay": payload["all_summary"]["replay_success_count"],
                "verify_only": args.verify_only,
            },
            ensure_ascii=False,
        )
    )
    exit_code = 0 if payload["core_passed_count"] == 12 else 1
    if temporary is not None:
        temporary.cleanup()
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
